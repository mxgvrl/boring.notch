//
//  ClipboardWatcher.swift
//  boringNotch
//
//  Polls the general pasteboard and adds copied content to the Shelf (clipboard history).
//

import AppKit
import Combine
import Defaults
import Foundation

@MainActor
final class ClipboardWatcher {
    static let shared = ClipboardWatcher()

    /// While true, pasteboard changes are ignored (e.g. synthetic copy during translation).
    var isSuspended = false

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var cancellables = Set<AnyCancellable>()
    private var observing = false

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    private init() {}

    func start() {
        if !observing {
            observing = true
            Defaults.publisher(.shelfClipboardHistory).sink { [weak self] _ in
                Task { @MainActor in self?.refresh() }
            }.store(in: &cancellables)
            Defaults.publisher(.boringShelf).sink { [weak self] _ in
                Task { @MainActor in self?.refresh() }
            }.store(in: &cancellables)
        }
        refresh()
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func refresh() {
        let enabled = Defaults[.boringShelf] && Defaults[.shelfClipboardHistory]
        if enabled {
            guard timer == nil else { return }
            lastChangeCount = NSPasteboard.general.changeCount
            let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
                Task { @MainActor in self?.tick() }
            }
            RunLoop.main.add(t, forMode: .common)
            timer = t
        } else {
            stop()
        }
    }

    /// Call right after the app writes to the pasteboard so the write is not imported.
    nonisolated func markOwnWrite() {
        let count = NSPasteboard.general.changeCount
        Task { @MainActor in self.lastChangeCount = count }
    }

    private func tick() {
        guard !isSuspended else { return }
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        let types = Set((pb.types ?? []).map { $0.rawValue })
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        // 1. Files
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let items: [ShelfItem] = urls.compactMap { url in
                guard let bookmark = try? Bookmark(url: url) else { return nil }
                return ShelfItem(kind: .file(bookmark: bookmark.data), isTemporary: false, fromClipboard: true)
            }
            if !items.isEmpty { ShelfStateViewModel.shared.add(items) }
            return
        }

        // 2. Images
        let imageData = pb.data(forType: .png) ?? pb.data(forType: .tiff)
        if let imageData {
            Task { @MainActor in
                var png = imageData
                if pb.data(forType: .png) == nil,
                   let rep = NSBitmapImageRep(data: imageData),
                   let converted = rep.representation(using: .png, properties: [:]) {
                    png = converted
                }
                let f = DateFormatter()
                f.dateFormat = "yyyy-MM-dd HH.mm.ss"
                let name = "Clipboard \(f.string(from: Date())).png"
                guard let url = await TemporaryFileStorageService.shared.createTempFile(for: .data(png, suggestedName: name)),
                      let bookmark = try? Bookmark(url: url) else { return }
                ShelfStateViewModel.shared.add([ShelfItem(kind: .file(bookmark: bookmark.data), isTemporary: true, fromClipboard: true)])
            }
            return
        }

        // 3. Text / links
        guard let raw = pb.string(forType: .string) else { return }
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty, text.count <= 100_000 else { return }
        if !text.contains(where: { $0.isWhitespace }),
           let url = URL(string: text),
           let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https", url.host != nil {
            ShelfStateViewModel.shared.add([ShelfItem(kind: .link(url: url), fromClipboard: true)])
        } else {
            ShelfStateViewModel.shared.add([ShelfItem(kind: .text(string: text), fromClipboard: true)])
        }
    }
}
